const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  cloudAccounts: () => ipcRenderer.invoke('cloud-accounts-list'),
  saveCloudAccount: account => ipcRenderer.invoke('cloud-accounts-save', account),
  deleteCloudAccount: accountId => ipcRenderer.invoke('cloud-accounts-delete', accountId),
  signOutCloudAccount: accountId => ipcRenderer.invoke('cloud-accounts-sign-out', accountId),
  setDefaultCloudAccount: accountId => ipcRenderer.invoke('cloud-accounts-set-default', accountId),
  verifyCloudAccount: accountId => ipcRenderer.invoke('cloud-accounts-verify', accountId),
  startGoogleOAuth: params => ipcRenderer.invoke('cloud-accounts-oauth-google', params),
  configureThunderbird: payload => ipcRenderer.invoke('cloud-accounts-configure-thunderbird', payload),
  launchRobosApp: appId => ipcRenderer.invoke('launch-robos-app', appId),
  githubAccounts: () => ipcRenderer.invoke('github-accounts-list'),
  saveGithubAccounts: selection => ipcRenderer.invoke('github-accounts-save', selection),
  addGithubAccount: () => ipcRenderer.invoke('github-accounts-add'),
  onShowGithubAccounts: callback => ipcRenderer.on('show-github-accounts', callback),
  ovpnAccounts: () => ipcRenderer.invoke('ovpn-accounts-list'),
  saveOvpnAccount: account => ipcRenderer.invoke('ovpn-accounts-save', account),
  deleteOvpnAccount: accountId => ipcRenderer.invoke('ovpn-accounts-delete', accountId),
  setDefaultOvpnAccount: accountId => ipcRenderer.invoke('ovpn-accounts-set-default', accountId),
  addOvpnProvider: provider => ipcRenderer.invoke('ovpn-providers-add', provider),
  syncOvpnProfiles: providerId => ipcRenderer.invoke('ovpn-profiles-sync', providerId),
  testOvpnAccount: payload => ipcRenderer.invoke('ovpn-accounts-test', payload),
  configSync: (call, opts) => ipcRenderer.invoke(`config-sync:${call}`, opts),
  takeOpenRequest: () => ipcRenderer.invoke('take-open-request'),
  onOpenRequest: callback => ipcRenderer.on('open-request', callback),
  getSchema:     ()        => ipcRenderer.invoke('get-schema'),
  loadSettings:  ()        => ipcRenderer.invoke('load-settings'),
  saveSettings:  (data)    => ipcRenderer.invoke('save-settings', data),
  getSetting:    (key)     => ipcRenderer.invoke('get-setting', key),
  setSetting:    (key, v)  => ipcRenderer.invoke('set-setting', key, v),
  aiApiStatus:   ()        => ipcRenderer.invoke('ai-api-status'),
  aiApiSaveKey:  (p, v)    => ipcRenderer.invoke('ai-api-save-key', p, v),
  aiApiInstall:  (list)    => ipcRenderer.invoke('ai-api-install', list),
});
