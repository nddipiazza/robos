'use strict';

// Synthesizes the ordered milestone registry (playthrough/milestones.json),
// the checkpoint-chained Cucumber feature (playthrough/features/checkpoint_playthrough.feature),
// and the core game-mechanic Cucumber feature suite (start_new_game, smoke_maps,
// npc_dialogues, shops, treasure_chests, random_encounters) from a parsed JRPG
// knowledge graph so the RobOS Game Playthrough viewer (packages/game-playthrough)
// and headless Cucumber runner can verify every mechanic and milestone.

const fs = require('fs');
const path = require('path');
const { slug } = require('./slug');

function inferMilestoneType(m) {
  if (m.type) return m.type;
  if (m.boss) return 'boss';
  const t = String(m.title || '');
  if (/\b(buy|purchase|shop|equip)\b/i.test(t)) return 'buy';
  if (/\b(chest|treasure|open)\b/i.test(t)) return 'chest';
  if (/\b(talk|speak|king|princess|queen|prince|sage|elder|canoe)\b/i.test(t)) return 'talk';
  return 'step';
}

function parseCoords(coordStr) {
  const m = String(coordStr || '').match(/\(?\s*(\d+)\s*,\s*(\d+)\s*\)?/);
  if (!m) return { col: 0, row: 0 };
  return { col: parseInt(m[1], 10), row: parseInt(m[2], 10) };
}

function buildPlaythroughMilestones(parsed) {
  const g = parsed.game || { title: 'JRPG', edition: 'NES' };
  const gameTitle = g.edition && g.edition !== 'unspecified' ? `${g.title} (${g.edition})` : g.title;
  const rawMilestones = Array.isArray(parsed.milestones) ? parsed.milestones : [];
  const milestones = [];

  rawMilestones.forEach((m, idx) => {
    const seq = idx + 1;
    const id = m.id || slug(m.title || `milestone-${seq}`);
    const name = m.title || m.name || `Milestone ${seq}`;
    const mapKey = slug(m.place || m.map || 'world-map');
    const mtype = inferMilestoneType(m);
    const tile = m.tile && typeof m.tile.col === 'number'
      ? { col: m.tile.col, row: m.tile.row }
      : parseCoords(m.coordinates);
    const flagName = m.boss
      ? `${slug(m.boss).replace(/-/g, '_')}_defeated`
      : `${id.replace(/-/g, '_')}_done`;
    const doneWhen = m.done_when || {
      kind: 'flag',
      flag: flagName,
    };
    const entry = {
      seq,
      index: seq,
      id,
      name,
      phase: mapKey,
      type: mtype,
      map: mapKey,
      tile,
      optional: Boolean(m.optional),
      min_level: Number(m.min_level || 1),
      done_when: doneWhen,
    };
    if (m.face) entry.face = m.face;
    if (m.boss) entry.boss = m.boss;
    if (Array.isArray(m.requires) && m.requires.length) entry.requires = m.requires;
    if (Array.isArray(m.grants) && m.grants.length) entry.grants = m.grants;
    milestones.push(entry);
  });

  return {
    _comment: 'Generated by robos-jrpg-parser — ordered objectives for the Player AI play-the-game mode and RobOS Game Playthrough viewer.',
    version: 1,
    game: gameTitle,
    total: milestones.length,
    milestones,
  };
}

function buildCheckpointFeature(parsed, milestonesDoc) {
  const doc = milestonesDoc || buildPlaythroughMilestones(parsed);
  const g = parsed.game || { title: 'JRPG' };
  const lines = [
    `Feature: ${g.title} Autonomous In-Engine AI Checkpoint Playthrough`,
    '  As a player or autonomous demo AI',
    `  I want the in-engine AI to play ${g.title} using only real user inputs`,
    '  From a fresh game or saved checkpoint state until each target milestone checkpoint is achieved',
    '  So that we can chain checkpoints together in RobOS Game Playthrough to prove milestone-by-milestone completion',
    '',
  ];

  const list = doc.milestones || [];
  list.forEach((m, idx) => {
    const num = String(m.seq || idx + 1).padStart(2, '0');
    const prev = idx > 0 ? list[idx - 1] : null;
    const prevNum = prev ? String(prev.seq || idx).padStart(2, '0') : '';
    const ckptName = `${num}-${m.id}`;
    const prevCkptName = prev ? `${prevNum}-${prev.id}` : '';

    lines.push(`  Scenario: Milestone ${num} - ${m.name}`);
    if (idx === 0) {
      lines.push('    Given create fresh game');
    } else {
      lines.push(`    Given the game state is loaded from checkpoint "${prevCkptName}"`);
    }
    lines.push(`    When the in-engine AI plays until checkpoint "${m.id}"`);
    lines.push(`    Then verify that game state is {"milestone_done": "${m.id}"}`);
    lines.push(`    And save game state to checkpoint "${ckptName}"`);
    lines.push('');
  });

  return lines.join('\n');
}

function buildMechanicFeatures(parsed) {
  const g = parsed.game || { title: 'JRPG' };
  const maps = Array.isArray(parsed.maps) ? parsed.maps : [];
  const shops = Array.isArray(parsed.shops) ? parsed.shops : [];
  const enemies = Array.isArray(parsed.enemies) ? parsed.enemies : [];
  const firstMap = maps[0] ? (maps[0].name || 'Coneria') : 'Coneria';
  const firstShop = shops[0] ? (shops[0].name || 'Coneria Weapon Shop') : 'Coneria Weapon Shop';
  const firstEnemy = enemies[0] ? (enemies[0].name || 'IMP') : 'IMP';
  const bossEnemy = (enemies.find((e) => /garland|boss|dragon/i.test(String(e.name || ''))) || {}).name || 'GARLAND';

  return {
    'start_new_game.feature': [
      `Feature: ${g.title} Start New Game and Party Creation`,
      '  Scenario: Start a New Game from TitleScreen and create the Light Warriors',
      '    Given the game is launched on "TitleScreen" in virtual display Xvfb',
      '    When the player selects NEW GAME on the title screen',
      '    Then the game transitions to "PartyCreate"',
      '    When the player creates the 4 Light Warriors and begins the quest',
      `    Then the game transitions to "${firstMap.replace(/\s+/g, '')}"`,
      '    And the party has 4 Light Warriors and 400 Gold',
      '',
    ].join('\n'),
    'smoke_maps.feature': [
      `Feature: ${g.title} Map Loading and Scene Transitions`,
      '  Scenario: Walk out of town onto the Overworld and enter Castle 1F and 2F',
      '    Given the game is launched on "Coneria" at tile (16, 21) facing "down" in virtual display Xvfb',
      '    When the hero moves down 3 tiles',
      '    Then the game transitions to "WorldMap"',
      '    When the party enters "ConeriaCastle1F" at tile (12, 19) facing "up"',
      '    And the hero moves up 1 tiles',
      '    Then the game transitions to "ConeriaCastle2F"',
      '',
    ].join('\n'),
    'npc_dialogues.feature': [
      `Feature: ${g.title} Town & Castle NPC Dialogues`,
      '  Scenario: Speak with Coneria villager and the King of Coneria',
      '    Given the game is launched on "Coneria" at tile (17, 20) facing "right" in virtual display Xvfb',
      '    When the player talks to the NPC in front of the hero',
      '    Then dialog is displayed with text containing "Coneria"',
      '    When the player advances the dialog page',
      '    And the party enters "ConeriaCastle2F" at tile (12, 5) facing "up"',
      '    And the player talks to the NPC in front of the hero',
      '    Then dialog is displayed with text containing "Garland"',
      '',
    ].join('\n'),
    'shops.feature': [
      `Feature: ${g.title} Town Shops (${firstShop})`,
      '  Scenario: Purchase and equip weapons, armor, and magic in Coneria',
      '    Given the game is launched on "Coneria" at tile (11, 11) facing "up" in virtual display Xvfb',
      '    When the hero moves up 1 tiles',
      '    Then dialog is displayed with text containing "Weapon Shop"',
      '    When the player advances the dialog page',
      '    Then the leader weapon is "Rapier"',
      '',
    ].join('\n'),
    'treasure_chests.feature': [
      `Feature: ${g.title} Dungeon Treasure Chests`,
      '  Scenario: Open treasure chests in the Temple of Fiends and verify persistence',
      '    Given the game is launched on "TempleOfFiends" at tile (3, 4) facing "up" in virtual display Xvfb',
      '    When the hero moves up 1 tiles',
      '    And the hero uses the "SEARCH" command on the chest',
      '    Then dialog is displayed with text containing "HEAL Potion"',
      '    When the player advances the dialog page',
      '    Then the item "HEAL Potion" is present in player inventory',
      '',
    ].join('\n'),
    'random_encounters.feature': [
      `Feature: ${g.title} Random Encounters (${firstEnemy}) and Boss Combat (${bossEnemy})`,
      `  Scenario: Defeat ${firstEnemy} in an encounter and defeat ${bossEnemy} in the Temple of Fiends`,
      '    Given the game is launched on "TempleOfFiends" at tile (20, 22) facing "up" in virtual display Xvfb',
      '    When the player talks to the NPC in front of the hero',
      '    Then dialog is displayed with text containing "Garland"',
      '    When the player advances the dialog page',
      `    Then a battle begins against "${bossEnemy}"`,
      '    When the party fights until the battle is won',
      '    Then Garland is defeated and Princess Sara is rescued',
      '',
    ].join('\n'),
  };
}

function writePlaythroughArtifacts(outDir, parsed) {
  const playDir = path.join(outDir, 'playthrough');
  const featDir = path.join(playDir, 'features');
  fs.mkdirSync(featDir, { recursive: true });

  const milestonesDoc = buildPlaythroughMilestones(parsed);
  const featureText = buildCheckpointFeature(parsed, milestonesDoc);
  const mechanicFeatures = buildMechanicFeatures(parsed);

  const milestonesPath = path.join(playDir, 'milestones.json');
  const featurePath = path.join(featDir, 'checkpoint_playthrough.feature');

  fs.writeFileSync(milestonesPath, JSON.stringify(milestonesDoc, null, 2) + '\n');
  fs.writeFileSync(featurePath, featureText);

  const mechanicFeaturePaths = [];
  for (const [fname, content] of Object.entries(mechanicFeatures)) {
    const fpath = path.join(featDir, fname);
    fs.writeFileSync(fpath, content);
    mechanicFeaturePaths.push(fpath);
  }

  return {
    milestonesPath,
    featurePath,
    mechanicFeaturePaths,
    milestoneCount: milestonesDoc.milestones.length,
  };
}

module.exports = {
  buildPlaythroughMilestones,
  buildCheckpointFeature,
  buildMechanicFeatures,
  writePlaythroughArtifacts,
};
