function discoverSystemLinuxPlugins() {
  try {
    const { getVstDirectoriesSnapshot } = require('./vst-directories');
    return getVstDirectoriesSnapshot().discoveredPlugins.map(p => ({
      name: p.name,
      fileName: p.fileName,
      format: p.format,
      dir: p.rootDir,
      path: p.path,
      source: p.source,
    }));
  } catch {
    return [];
  }
}

