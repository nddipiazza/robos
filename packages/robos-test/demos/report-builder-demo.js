'use strict';
const path = require('path');
const fs   = require('fs');

const scenarios  = require('../lib/scenarios');
const { runDemo } = require('../lib/demo-runner');
const { evalJS } = require('../lib/snapshot');

/**
 * Pre-seed ~/.config/robos/reports/ with realistic saved reports so the
 * history view has content on launch. We don't click "Generate Report" in the
 * demo since gh copilot isn't sophisticated enough here to produce a real
 * report — instead we show the saved-reports flow.
 */
function seedReports(sandboxHome) {
  const dir = path.join(sandboxHome, '.config', 'robos', 'reports');
  fs.mkdirSync(dir, { recursive: true });

  const reports = [
    {
      id: '1745600000000-prs_per_developer',
      name: 'PRs per developer — last 30 days',
      query: 'How many PRs did each developer merge in the last 30 days?',
      savedAt: Date.now() - 2 * 86_400_000,
      content: `# PRs per developer — last 30 days\n\n**testuser** led the sprint with 8 merged PRs, focused on the worker-pool refactor and the TTL overflow fix.\n**alice-dev** merged 5 PRs — the fleet health endpoint and two scheduler priority cleanups.\n**bob-docs** merged 3 PRs — all documentation and dashboard polish.\n\n| Developer | Merged PRs | Lines | Review latency |\n|-----------|------------|-------|---------------|\n| testuser  | 8          | +1240 / -420 | 4h median |\n| alice-dev | 5          | +860 / -180  | 6h median |\n| bob-docs  | 3          | +210 / -30   | 2h median |\n\n**Observation:** review latency is healthy across the board. No PR sat longer than 24h.`,
    },
    {
      id: '1745400000000-stuck_reviews',
      name: 'Stuck reviews — open > 2 days',
      query: 'Show me tasks stuck in review for more than 2 days',
      savedAt: Date.now() - 5 * 86_400_000,
      content: `# Stuck reviews — open > 2 days\n\nTwo PRs have sat in review for more than 48 hours:\n\n- **#12 — WIP: Scheduler queue visualization dashboard** (3 days, testuser)\n  Draft with conflicting merge. Needs rebase before review can proceed.\n- **#14 — Fix CAS blob TTL calculation overflow** (2.5 days, testuser)\n  CI is failing. Blocked on a flaky test that needs investigation.\n\nNo tickets stuck in Triage. Flow is healthy everywhere else.`,
    },
    {
      id: '1745200000000-close_rate',
      name: 'Close rate comparison — this vs last month',
      query: 'Compare issue close rate this month vs last month',
      savedAt: Date.now() - 8 * 86_400_000,
      content: `# Close rate — month over month\n\n**April (so far):** 18 issues closed, 22 opened → net +4\n**March:** 31 closed, 26 opened → net –5\n\nWe\'re slightly ahead of last month on net, but opening rate is up 35%. Drill into the "bug" label: 12 of April\'s 22 new issues are bugs, vs 7 of 26 in March. The worker-pool refactor landed a cluster of new bug reports that we\'re now working through.`,
    },
  ];

  for (const r of reports) {
    fs.writeFileSync(path.join(dir, `${r.id}.json`), JSON.stringify(r, null, 2));
  }
}

const SCRIPT = [
  {
    narration: 'RobOS Report Builder answers questions about your project in plain English — sprint velocity, stuck reviews, close-rate comparisons — generated by an AI agent that reads your task server live.',
    js: null, minHold: 5500,
  },
  {
    narration: 'Type a question. The example chips on the right cover the most common ones — PRs per developer, stuck reviews, workload distribution — each wired up to run instantly.',
    js: null, minHold: 5500,
  },
  {
    narration: 'Open the Saved Reports panel to see everything the team has generated before.',
    js: `(() => {
      const btn = document.getElementById('btn-history');
      if (btn) btn.click();
    })();`,
    minHold: 4000,
  },
  {
    narration: 'Three reports archived — PRs per developer, stuck reviews, close rate month over month. Click any one to reload it instantly, no re-generation needed.',
    js: `(async () => {
      await new Promise(r => setTimeout(r, 600));
      const items = document.querySelectorAll('.history-item');
      if (items[0]) items[0].click();
    })();`,
    minHold: 6000,
  },
  {
    narration: 'The full Markdown-rendered report — headers, tables, narrative observations — exactly as the AI generated it. Not a template, not a dashboard. A written answer.',
    js: null, minHold: 6000,
  },
  {
    narration: 'Every report is saved automatically and can be re-run with updated data. Share the URL, paste it into a stand-up, drop it into a retrospective.',
    js: null, minHold: 5000,
  },
  {
    narration: 'Report Builder is how RobOS turns "can you pull that number for me?" into a thirty-second ask for anyone on the team.',
    js: null, minHold: 4500,
  },
];

runDemo({
  slug: 'report-builder',
  appId: 'report-builder',
  windowTitle: 'Report Builder',
  scenario: scenarios['github-task-server'],
  prelaunch: async (app) => {
    seedReports(app.sandboxHome);
    await evalJS(app.port, `window.location.reload()`);
  },
  postSettle: 1800,
  script: SCRIPT,
}).catch(err => { console.error(err); process.exit(1); });
